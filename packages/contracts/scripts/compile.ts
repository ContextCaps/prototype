import solc from "solc";
import { readFileSync, mkdirSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

export function compileRegistry() {
  const source = readFileSync(new URL("../src/CapabilityRegistry.sol", import.meta.url), "utf8");
  const input = { language: "Solidity", sources: { "CapabilityRegistry.sol": { content: source } }, settings: {
    optimizer: { enabled: true, runs: 200 }, evmVersion: "shanghai",
    outputSelection: { "*": { "*": ["abi", "evm.bytecode.object", "evm.deployedBytecode.object"] } },
  } };
  const output = JSON.parse(solc.compile(JSON.stringify(input)));
  const errors = (output.errors ?? []).filter((error: { severity: string }) => error.severity === "error");
  if (errors.length) throw new Error(errors.map((error: { formattedMessage: string }) => error.formattedMessage).join("\n"));
  const compiled = output.contracts["CapabilityRegistry.sol"].CapabilityRegistry;
  return { contractName: "CapabilityRegistry", compilerVersion: solc.version(), abi: compiled.abi,
    bytecode: `0x${compiled.evm.bytecode.object}`, deployedBytecode: `0x${compiled.evm.deployedBytecode.object}` };
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const artifact = compileRegistry();
  const out = new URL("../artifacts/", import.meta.url);
  mkdirSync(out, { recursive: true });
  writeFileSync(new URL("CapabilityRegistry.json", out), JSON.stringify(artifact, null, 2) + "\n");
  writeFileSync(new URL("../../contract-sdk/src/abi.ts", import.meta.url),
    `// Generated by npm run contracts:compile.\nexport const capabilityRegistryAbi = ${JSON.stringify(artifact.abi, null, 2)} as const;\n`);
  console.log(`Compiled ${artifact.contractName} with ${artifact.compilerVersion}`);
}
